/* Extract the questionnaire SEGMENTS field sets from
   questionnaire-form.html into partners/segments-data.js, so the
   standalone Partner Portal's questionnaire renders the EXACT
   approved question sets the public form uses — one source of
   truth, never a hand-copied drift. Re-run after any approved
   change to questionnaire-form.html:
     node scripts/extract-segments.mjs
   The output file is committed; the portal loads it as a plain
   script (window.IEC_SEGMENTS). */

import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';

const src = await readFile(new URL('../questionnaire-form.html', import.meta.url), 'utf8');
const start = src.indexOf('var SEGMENTS = {');
if (start < 0) throw new Error('SEGMENTS literal not found');
const aliasAt = src.indexOf('SEGMENTS["nonprofit"]', start);
if (aliasAt < 0) throw new Error('nonprofit alias not found');
const end = src.indexOf('(function () {', aliasAt);
if (end < 0) throw new Error('IIFE after SEGMENTS not found');
const literal = src.slice(start, end).trim();

const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(literal + '\nthis.__SEGMENTS = SEGMENTS;', sandbox);
const segments = sandbox.__SEGMENTS;
const slugs = Object.keys(segments);
if (!slugs.length) throw new Error('no segments extracted');
for (const slug of slugs) {
  const s = segments[slug];
  if (!s || !Array.isArray(s.sections) || !s.sections.length) {
    throw new Error(`segment ${slug} has no sections`);
  }
}

const out = [
  '/* IEC Partner Portal — questionnaire field sets.',
  '   GENERATED by scripts/extract-segments.mjs from',
  '   questionnaire-form.html (the approved public form). Do not',
  '   hand-edit: change the form, then re-run the extractor. */',
  'window.IEC_SEGMENTS = ' + JSON.stringify(segments, null, 1) + ';',
  ''
].join('\n');
await writeFile(new URL('../partners/segments-data.js', import.meta.url), out);
console.log(`segments-data.js written: ${slugs.join(', ')}`);
