/* =====================================================================
   Build api/_cnda-content.js from the ONE source of truth for the
   central IEC CNDA's legal text: cnda.html at the repo root (the
   central signing page whose form posts to the medexec-app submit
   flow). The Partner Portal's client-CNDA step renders and records
   the SAME instrument for partner-link owners — the text is
   extracted MECHANICALLY from cnda.html, never retyped, and this
   script PROVES the extraction before it writes anything:

   - both arrays are present, equal length, and carry the
     instrument's placeholders and IEC execution block;
   - a sample executed document rendered from the generated
     helpers substitutes every placeholder (no bracketed token
     survives) and carries both signature blocks;
   - the SHA-256 of the extracted texts is stamped into the
     module, so any drift between cnda.html and the generated
     copy is detectable (the test suite re-derives it).

   Run: node scripts/build-cnda-content.mjs
   ===================================================================== */

import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import vm from 'node:vm';

const SRC = new URL('../cnda.html', import.meta.url);
const OUT = new URL('../api/_cnda-content.js', import.meta.url);

const html = await readFile(SRC, 'utf8');
const start = html.indexOf('var agreementTexts');
const end = html.indexOf('var ORIGIN_LABELS');
if (start < 0 || end < 0 || end <= start) {
  throw new Error('cnda.html: agreementTexts / ORIGIN_LABELS markers not found — extraction aborted');
}
const slice = html.slice(start, end);
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(`${slice}\n;__out = { texts: agreementTexts, titles: sectionTitles };`, sandbox);
const { texts, titles } = sandbox.__out;

const fail = (msg) => { throw new Error(`build-cnda-content: ${msg}`); };
if (!Array.isArray(texts) || !Array.isArray(titles)) fail('extracted values are not arrays');
if (texts.length !== titles.length) fail(`texts (${texts.length}) and titles (${titles.length}) differ in length`);
if (texts.length < 10) fail(`suspiciously few sections (${texts.length})`);
if (!texts[0].includes('[EFFECTIVE DATE]') || !texts[0].includes('[COUNTERPARTY NAME]')) {
  fail('preamble placeholders missing — the instrument text changed shape');
}
if (!texts[texts.length - 1].includes('Mohammed Morgan, MD')) {
  fail('execution block no longer carries the IEC signatory — refusing to generate');
}
for (const ph of ['[STATE]', '[ENTITY TYPE/STATE]', '[ADDRESS]', '[PURPOSE]']) {
  if (!texts.join('\n').includes(ph)) fail(`placeholder ${ph} missing from the instrument`);
}

const sha = createHash('sha256').update(JSON.stringify({ texts, titles })).digest('hex');

const module_ = `/* =====================================================================
   GENERATED by scripts/build-cnda-content.mjs from cnda.html —
   DO NOT EDIT BY HAND. The legal text of the central IEC CNDA
   (General CNDA and Procuring Party Agreement) lives in cnda.html
   and in the medexec-app submit flow it posts to; this module is
   the Partner Portal's mechanically extracted copy of the SAME
   text, used by the portal's client-CNDA step (api/_client-cnda.js)
   so a partner-link owner signs the identical instrument. Regenerate
   after any change to cnda.html; the content hash below is asserted
   by scripts/partner-portal-cnda.test.mjs.
   Source: cnda.html · texts SHA-256: ${sha}
   ===================================================================== */

export const CNDA_TEXT_SHA256 = ${JSON.stringify(sha)};

export const CNDA_TEXTS = ${JSON.stringify(texts, null, 2)};

export const CNDA_TITLES = ${JSON.stringify(titles, null, 2)};

/* The instrument's own defaults (cnda.html's form ships them):
   IEC is a Massachusetts corporation, and the standard purpose
   text is the form's pre-filled value — neither is invented here. */
export const CNDA_IEC_STATE = 'Massachusetts';
export const CNDA_DEFAULT_PURPOSE = 'the evaluation of, and discussions regarding, the IEC Assets, including product demonstrations, pilots, and related business discussions';

/* IEC's signatory of record on the instrument. */
export const CNDA_SIGNATORY = {
  name: 'Mohammed Morgan, MD',
  title: 'Founder & CEO, IEC, Inc.',
  org: 'International Empire Consultants, Inc.',
  address: '923 Hyde Park Ave, Boston, MA 02136',
  email: 'info@iecincglobal.com'
};

export function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
}

/* Placeholder substitution — mirrors cnda.html's fillAgreementText
   exactly (an unfilled field leaves its bracketed placeholder). */
export function fillCndaText(text, values) {
  const map = {
    '[EFFECTIVE DATE]': values.effectiveDate || '[EFFECTIVE DATE]',
    '[STATE]': values.iecState || '[STATE]',
    '[COUNTERPARTY NAME]': values.party || '[COUNTERPARTY NAME]',
    '[ENTITY TYPE/STATE]': values.entityTypeState || '[ENTITY TYPE/STATE]',
    '[ADDRESS]': values.address || '[ADDRESS]',
    '[PURPOSE]': values.purpose || '[PURPOSE]'
  };
  let out = String(text);
  for (const [ph, v] of Object.entries(map)) out = out.split(ph).join(v);
  return out;
}

/* The executed copy — mirrors cnda.html's buildSignedHtml: every
   section but the last text (the blank execution text) renders
   with its title, then the constructed Execution section. IEC's
   block carries DrMorgan's signature: the handwritten signature
   image of record (api/_assets/iec-signature.png, byte-identical
   to the asset the central flow stamps onto executed copies)
   when the caller supplies it as a data URI, otherwise his typed
   name — the same fallback the central renderer uses. The IEC
   date is the date the executed copy is issued (the record's
   IEC signing date), never the client-entered Effective Date. */
export function buildCndaDocumentHtml(values, { iecSignatureImg = '', iecDate = '' } = {}) {
  const sections = CNDA_TEXTS.slice(0, CNDA_TEXTS.length - 1).map((text, index) => {
    const heading = index === 0 ? '' : \`<h2>\${escapeHtml(CNDA_TITLES[index])}</h2>\`;
    return \`<section\${index === 0 ? ' class="intro"' : ''}>\${heading}<p>\${escapeHtml(fillCndaText(text, values))}</p></section>\`;
  }).join('');
  const iecSig = iecSignatureImg
    ? \`<p>Signature: <img src="\${iecSignatureImg}" alt="Mohammed Morgan, MD" style="height:44px;vertical-align:middle"></p>\`
    : '<p>Signature: <em>Mohammed Morgan, MD</em></p>';
  const iecBlock = '<div><h3>International Empire Consultants, Inc.</h3>'
    + '<p>(Pre-signed by IEC)</p>'
    + iecSig
    + '<p>Name: Mohammed Morgan, MD</p>'
    + '<p>Title: Founder &amp; CEO</p>'
    + \`<p>Date: \${escapeHtml(iecDate)}</p></div>\`;
  const cpBlock = \`<div><h3>\${escapeHtml(values.party)}</h3><p>Signature: <em>\${escapeHtml(values.signature)}</em></p><p>Name: \${escapeHtml(values.name)}</p><p>Title: \${escapeHtml(values.title || '—')}</p><p>Date: \${escapeHtml(values.date)}</p></div>\`;
  const signatureBlock = '<section class="execution"><h2>Execution</h2><p><strong>IN WITNESS WHEREOF</strong>, the Parties have executed this Agreement as of the Effective Date.</p><div class="signatures">'
    + iecBlock + cpBlock + '</div></section>';
  return '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>IEC General CNDA and Procuring Party Agreement</title></head><body><header><h1>General CNDA and Procuring Party Agreement</h1><p>International Empire Consultants, Inc. and '
    + escapeHtml(values.party) + '</p></header>' + sections + signatureBlock + '</body></html>';
}
`;

await writeFile(OUT, module_);
console.log(`wrote api/_cnda-content.js — ${texts.length} sections, sha256 ${sha.slice(0, 16)}…`);

/* Round-trip proof: render a sample executed document from the
   generated module and assert full substitution. */
const gen = await import(OUT.href + '?proof=1');
const sample = gen.buildCndaDocumentHtml({
  effectiveDate: '2026-11-21', iecState: 'Massachusetts', party: 'Proof Biz LLC',
  entityTypeState: 'Massachusetts limited liability company', address: '1 Proof St, Boston, MA',
  purpose: gen.CNDA_DEFAULT_PURPOSE, name: 'Olivia Owner', title: 'Owner',
  date: '2026-11-21', signature: 'Olivia Owner'
}, { iecDate: '2026-11-21' });
for (const ph of ['[EFFECTIVE DATE]', '[STATE]', '[COUNTERPARTY NAME]', '[ENTITY TYPE/STATE]', '[ADDRESS]', '[PURPOSE]']) {
  if (sample.includes(ph)) fail(`sample executed document still carries ${ph}`);
}
if (!sample.includes('Proof Biz LLC') || !sample.includes('Mohammed Morgan, MD')) {
  fail('sample executed document is missing a signature block');
}
console.log('round-trip proof passed: sample executed document fully substituted');
